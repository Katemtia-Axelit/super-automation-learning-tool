def _pick_free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _copy_static_assets(src_static: Path, dst_static: Path) -> None:
    """Mirror the strict static allowlist into the synthetic root.

    Reject symlinks/reparse points and skip anything outside the
    allowlist. Never overwrite or expose real notes/config/data.
    """
    dst_static.mkdir(parents=True, exist_ok=True)
    for top_name in _STATIC_ALLOWLIST:
        src = src_static / top_name
        if not src.is_file():
            continue
        if sandbox_env._is_reparse(src):  # type: ignore[attr-defined]
            raise ValueError(f"Refusing symlink/reparse: {src}")
        shutil.copyfile(src, dst_static / top_name, follow_symlinks=False)
    for sub in _STATIC_DIR_ALLOWLIST:
        src_dir = src_static / sub
        dst_dir = dst_static / sub
        if not src_dir.exists():
            continue
        if sandbox_env._is_reparse(src_dir):  # type: ignore[attr-defined]
            raise ValueError(f"Refusing symlink/reparse dir: {src_dir}")
        for dirpath, _dirs, files in os.walk(src_dir, followlinks=False):
            rel = Path(dirpath).relative_to(src_dir)
            target_dir = dst_dir / rel
            target_dir.mkdir(parents=True, exist_ok=True)
            for name in files:
                src_file = Path(dirpath) / name
                if sandbox_env._is_reparse(src_file):  # type: ignore[attr-defined]
                    raise ValueError(
                        f"Refusing symlink/reparse file: {src_file}"
                    )
                shutil.copyfile(
                    src_file, target_dir / name, follow_symlinks=False
                )


def _copy_index_html(src_html: Path, dst_html: Path) -> None:
    """Copy src/index.html verbatim into temp root/index.html.

    This is HTML content only; no symlinks, no references to project
    paths outside /static/. The real Factory serves it via legacy_compat.
    """
    if sandbox_env._is_reparse(src_html):  # type: ignore[attr-defined]
        raise ValueError(f"Refusing symlink/reparse: {src_html}")
    dst_html.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src_html, dst_html, follow_symlinks=False)


def _augment_seed(db_path: Path) -> None:
    """Insert a handful of additional unlocked tasks with sensible times.

    Multi-draw needs >=3 in-budget candidates with distinct ids. The base
    sandbox_env.seed gives us only 2 unlocked tasks (id 1, 3). We add
    a few more inside the SAME temp DB; nothing outside it.
    """
    conn = sqlite3.connect(db_path)
    try:
        extras = [
            (10, "synthetic-multi-alpha", 5, 10, "study"),
            (11, "synthetic-multi-beta", 4, 12, "study"),
            (12, "synthetic-multi-gamma", 3, 8, "rest"),
            (13, "synthetic-multi-delta", 6, 14, "study"),
        ]
        for tid, name, priority, minutes, cat in extras:
            conn.execute(
                """
                INSERT OR IGNORE INTO tasks
                  (id, name, priority, estimated_time, category,
                   energy_required, is_unlocked, completed, in_discard_pile)
                VALUES (?, ?, ?, ?, ?, 'medium', 1, 0, 0)
                """,
                (tid, name, priority, minutes, cat),
            )
        conn.commit()
    finally:
        conn.close()


def _install_synthetic_bootstrap(tmp_root: Path) -> Path:
    """Copy the audit module + bootstrap wrapper into the synthetic root.

    The bootstrap installs ``sys.addaudithook`` **inside** the child process
    before ``run_app.py`` executes, so every sqlite/file access the server
    performs is recorded from the inside — no runner-side observation of
    production files is needed (or permitted).
    """
    if not AUDIT_MODULE.is_file():
        raise FileNotFoundError("synthetic audit module missing: " + str(AUDIT_MODULE))
    shutil.copyfile(
        AUDIT_MODULE, tmp_root / AUDIT_MODULE_NAME, follow_symlinks=False
    )
    bootstrap = tmp_root / BOOTSTRAP_NAME
    bootstrap.write_text(BOOTSTRAP_TEMPLATE, encoding="utf-8")
    return bootstrap


def _child_env(tmp_root: Path) -> dict:
    """Environment for the synthetic child process.

    Filters secrets and points the audit at the real project root so the
    audit can *detect* (not read) any accidental access.
    """
    env = {
        k: v for k, v in os.environ.items()
        if not (
            k.upper() in {"PYTHONPATH", "PYTHONHOME"}
            or any(secret in k.upper()
                   for secret in ("API_KEY", "TOKEN", "SECRET"))
        )
    }
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["SAL_AUDIT_REAL_ROOT"] = str(PROJECT_ROOT.resolve())
    env["SAL_AUDIT_SYNTHETIC_ROOT"] = str(tmp_root.resolve())
    env["SAL_AUDIT_OUTPUT"] = str(
        (tmp_root / AUDIT_OUTPUT_NAME).resolve()
    )
    return env



"""M1.4A safe synthetic Factory server fixture.

Runs an isolated Flask app built from the project's real Factory, served out
of a temporary synthetic root that is created fresh each invocation and
torn down when the caller exits this context manager.

Design contract (per LT_M1_4A_FACTORY_FULLPAGE_BOOT_20261011):

- 100 % TEMP synthetic root under %TEMP% (windows default /tmp elsewhere).
- Never read or write the project's actual data/task_publisher.db*,
  src/notes/**, or config/config.json.
- Source-only copy of ``server/`` (``.py`` files). HTML content copied
  from src/index.html into temp root/index.html. A strict allowlist of
  static frontend assets is mirrored into temp root/static.
- Synthetic SQLite is built by ``tests/characterize/sandbox_env.seed`` and
  then augmented with extra unlocked tasks so ``/api/gacha/multi-draw``
  has enough candidates for the in-page smoke test. Augmentation only
  touches the temp synthetic DB.
- Random free TCP port on 127.0.0.1 only (NOT 5000). Never bound to a
  public interface. No external network exposure.
- Health gate (``/api/health``) blocks the caller until the server is
  serving real responses, then yields the base URL.
- Robust teardown: SIGINT/SIGTERM/SIGBREAK inside the manager, plus a
  try/finally that always terminates the child process and removes the
  temp root, even on assertion failures or tracebacks.

This fixture reuses ``tests/characterize/sandbox_env`` for source copy,
seed, and port-picking without modifying it.
"""

